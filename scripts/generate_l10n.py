LANGS = ["en", "tr", "es", "zh-Hans", "hi", "ar", "pt-BR", "fr", "de", "ja"]

def build():
    strings = {}
    for key, locs in STRINGS.items():
        localizations = {}
        for lang in LANGS:
            value = locs.get(lang) or locs["en"]
            localizations[lang] = {
                "stringUnit": {
                    "state": "translated",
                    "value": value,
                }
            }
        strings[key] = {
            "extractionState": "manual",
            "localizations": localizations,
        }
    catalog = {
        "sourceLanguage": "en",
        "strings": strings,
        "version": "1.0",
    }
    out = Path("/Users/cagataygecko/Desktop/UP 25/UP 25/Localizable.xcstrings")
    out.write_text(json.dumps(catalog, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {out} with {len(strings)} keys × {len(LANGS)} langs")

if __name__ == "__main__":
    build()
